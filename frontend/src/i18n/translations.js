export function t(lang, path) {
  const keys = path.split('.');
  let val = translations[lang] || translations.en;
  for (const k of keys) {
    val = val?.[k];
    if (val === undefined) {
      // Fall back to English
      let en = translations.en;
      for (const k2 of keys) en = en?.[k2];
      return en ?? path;
    }
  }
  return val ?? path;
}
